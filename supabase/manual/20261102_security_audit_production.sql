create or replace function public.current_client_ip()
returns text
language sql
stable
set search_path = public, pg_temp
as $$
  select trim(split_part(coalesce(
    nullif(current_setting('request.headers', true)::json->>'x-forwarded-for', ''),
    nullif(current_setting('request.headers', true)::json->>'x-real-ip', ''),
    ''
  ), ',', 1));
$$;

create or replace function public.consume_login_rate_limit(p_username text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_ip text := public.current_client_ip();
  v_user text := lower(trim(coalesce(p_username, '')));
  v_user_bucket text;
  v_ip_bucket text;
  v_row public.attendance_login_rate_limits%rowtype;
  v_now timestamptz := now();
  v_blocked boolean := false;
begin
  if v_ip = '' then
    return false;
  end if;

  v_user_bucket := 'login-user:' || encode(digest(v_ip || '|' || v_user, 'sha256'), 'hex');
  v_ip_bucket := 'login-ip:' || encode(digest(v_ip, 'sha256'), 'hex');

  perform pg_advisory_xact_lock(hashtext(v_user_bucket));
  select * into v_row
  from public.attendance_login_rate_limits
  where bucket_key = v_user_bucket
  for update;

  if found and v_row.blocked_until is not null and v_row.blocked_until > v_now then
    v_blocked := true;
  else
    if not found or v_row.window_started_at < v_now - interval '5 minutes' then
      insert into public.attendance_login_rate_limits(bucket_key, window_started_at, attempts, blocked_until, updated_at)
      values(v_user_bucket, v_now, 1, null, v_now)
      on conflict(bucket_key) do update
        set window_started_at = excluded.window_started_at,
            attempts = 1,
            blocked_until = null,
            updated_at = excluded.updated_at;
    elsif v_row.attempts >= 10 then
      update public.attendance_login_rate_limits
      set blocked_until = v_now + interval '10 minutes', updated_at = v_now
      where bucket_key = v_user_bucket;
      v_blocked := true;
    else
      update public.attendance_login_rate_limits
      set attempts = attempts + 1, updated_at = v_now
      where bucket_key = v_user_bucket;
    end if;
  end if;

  perform pg_advisory_xact_lock(hashtext(v_ip_bucket));
  select * into v_row
  from public.attendance_login_rate_limits
  where bucket_key = v_ip_bucket
  for update;

  if found and v_row.blocked_until is not null and v_row.blocked_until > v_now then
    v_blocked := true;
  else
    if not found or v_row.window_started_at < v_now - interval '5 minutes' then
      insert into public.attendance_login_rate_limits(bucket_key, window_started_at, attempts, blocked_until, updated_at)
      values(v_ip_bucket, v_now, 1, null, v_now)
      on conflict(bucket_key) do update
        set window_started_at = excluded.window_started_at,
            attempts = 1,
            blocked_until = null,
            updated_at = excluded.updated_at;
    elsif v_row.attempts >= 60 then
      update public.attendance_login_rate_limits
      set blocked_until = v_now + interval '10 minutes', updated_at = v_now
      where bucket_key = v_ip_bucket;
      v_blocked := true;
    else
      update public.attendance_login_rate_limits
      set attempts = attempts + 1, updated_at = v_now
      where bucket_key = v_ip_bucket;
    end if;
  end if;

  return v_blocked;
end;
$$;

create or replace function public.reset_login_rate_limit(p_username text)
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_ip text := public.current_client_ip();
  v_user text := lower(trim(coalesce(p_username, '')));
  v_user_bucket text;
