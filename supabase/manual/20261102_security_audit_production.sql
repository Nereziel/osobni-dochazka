create or replace function public.login_attendance_user(
  p_username text,
  p_pin text,
  p_remember boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_clean_user text;
  v_user_key text;
  v_profile public.attendance_profiles%rowtype;
  v_cred public.attendance_credentials%rowtype;
  v_is_valid boolean := false;
  v_raw_token text;
  v_token_hash text;
  v_expires_at timestamptz;
begin
  if public.consume_login_rate_limit(p_username) then
    return jsonb_build_object(
      'success', false,
      'error', 'rate_limited',
      'message', 'Příliš mnoho pokusů o přihlášení. Zkus to později.'
    );
  end if;

  if p_username is null or trim(p_username) = '' or p_pin is null or length(p_pin) < 1 then
    perform crypt(coalesce(p_pin, 'dummy_pin'), '$2a$10$abcdefghijklmnopqrstuuABCDEFGHIJKLMNOPQRSTUUWXYZ123456');
    return jsonb_build_object('success', false, 'error', 'invalid_credentials', 'message', 'Neplatné přihlašovací údaje.');
  end if;

  v_clean_user := lower(trim(regexp_replace(p_username, '[^a-zA-Z0-9._-]', '', 'g')));
  if length(v_clean_user) < 1 then
    perform crypt(p_pin, '$2a$10$abcdefghijklmnopqrstuuABCDEFGHIJKLMNOPQRSTUUWXYZ123456');
    return jsonb_build_object('success', false, 'error', 'invalid_credentials', 'message', 'Neplatné přihlašovací údaje.');
  end if;
  v_user_key := 'user:' || v_clean_user;

  select * into v_profile from public.attendance_profiles where user_key = v_user_key;
  if not found then
    perform crypt(p_pin, '$2a$10$abcdefghijklmnopqrstuuABCDEFGHIJKLMNOPQRSTUUWXYZ123456');
    return jsonb_build_object('success', false, 'error', 'invalid_credentials', 'message', 'Neplatné přihlašovací údaje.');
  end if;

  select * into v_cred
  from public.attendance_credentials
  where user_key = v_user_key
  for update;
  if not found then
    perform crypt(p_pin, '$2a$10$abcdefghijklmnopqrstuuABCDEFGHIJKLMNOPQRSTUUWXYZ123456');
    return jsonb_build_object('success', false, 'error', 'invalid_credentials', 'message', 'Neplatné přihlašovací údaje.');
  end if;

  v_is_valid := coalesce(crypt(p_pin, v_cred.pin_password_hash) = v_cred.pin_password_hash, false);
  if not v_is_valid then
    update public.attendance_credentials
    set failed_login_count = least(failed_login_count + 1, 1000000),
        last_failed_login_at = now(),
        locked_until = null,
        updated_at = now()
    where user_key = v_user_key;
    return jsonb_build_object('success', false, 'error', 'invalid_credentials', 'message', 'Neplatné přihlašovací údaje.');
  end if;

  update public.attendance_credentials
  set failed_login_count = 0, locked_until = null, updated_at = now()
  where user_key = v_user_key;
  perform public.reset_login_rate_limit(v_clean_user);

  v_raw_token := encode(gen_random_bytes(32), 'hex');
  v_token_hash := encode(digest(v_raw_token, 'sha256'), 'hex');
  v_expires_at := case when coalesce(p_remember, false)
    then now() + interval '30 days'
    else now() + interval '1 day'
  end;

  insert into public.attendance_sessions(user_key, token_hash, expires_at, created_at, last_used_at, user_agent)
  values(v_user_key, v_token_hash, v_expires_at, now(), now(), public.current_client_user_agent());

  return jsonb_build_object(
    'success', true,
    'session_token', v_raw_token,
    'user_key', v_profile.user_key,
    'username', v_profile.username,
    'display_name', v_profile.display_name,
    'role', v_profile.role,
    'expires_at', v_expires_at
  );
end;
$$;

drop function if exists public.admin_reset_user_pin(text, text);
create function public.admin_reset_user_pin(
  p_target_user_key text,
  p_new_pin text,
  p_admin_pin text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_actor text;
  v_bcrypt text;
begin
  v_actor := public.assert_admin_step_up(p_admin_pin);
  if p_target_user_key = v_actor then
    raise exception 'Vlastní PIN změň přes funkci Změnit PIN, která ověřuje původní PIN.';
  end if;
  if p_new_pin is null or length(p_new_pin) < 6 then
    raise exception 'PIN/heslo musí mít alespoň 6 znaků.';
  end if;

  v_bcrypt := crypt(p_new_pin, gen_salt('bf', 10));
  update public.attendance_credentials
  set pin_password_hash = v_bcrypt, failed_login_count = 0, locked_until = null, updated_at = now()
  where user_key = p_target_user_key;
  if not found then
    raise exception 'Uživatel nebyl nalezen.';
  end if;

  update public.attendance_sessions
  set revoked_at = now()
  where user_key = p_target_user_key and revoked_at is null;

  perform public.log_attendance_security_event('admin_reset_user_pin', p_target_user_key);
  return true;
end;
$$;

drop function if exists public.admin_change_user_role(text, text);
create function public.admin_change_user_role(
  p_target_user_key text,
  p_new_role text,
  p_admin_pin text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_actor text;
  v_other_admins integer;
  v_old_role text;
begin
  v_actor := public.assert_admin_step_up(p_admin_pin);
  if p_new_role not in ('admin', 'employee') then
    raise exception 'Neplatná role.';
  end if;

  perform pg_advisory_xact_lock(hashtext('attendance_admin_guard'));
  select role into v_old_role from public.attendance_profiles where user_key = p_target_user_key for update;
  if not found then
    raise exception 'Uživatel nebyl nalezen.';
  end if;

  if p_new_role = 'employee' and v_old_role = 'admin' then
    select count(*) into v_other_admins
    from public.attendance_profiles
    where role = 'admin' and user_key <> p_target_user_key;
    if v_other_admins = 0 then
      raise exception 'Operaci nelze provést: Nelze odebrat roli poslednímu administrátorovi v systému.';
    end if;
  end if;

  update public.attendance_profiles
  set role = p_new_role, updated_at = now()
  where user_key = p_target_user_key;

  perform public.log_attendance_security_event(
    'admin_change_user_role',
    p_target_user_key,
    jsonb_build_object('from', v_old_role, 'to', p_new_role)
  );
  return true;
end;
$$;

drop function if exists public.admin_delete_user(text);
create function public.admin_delete_user(
  p_target_user_key text,
  p_admin_pin text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_actor text;
  v_other_admins integer;
  v_target_role text;
begin
  v_actor := public.assert_admin_step_up(p_admin_pin);
  if p_target_user_key = v_actor then
    raise exception 'Nemůžeš smazat svůj vlastní přihlášený administrátorský účet.';
  end if;

  perform pg_advisory_xact_lock(hashtext('attendance_admin_guard'));
  select role into v_target_role
  from public.attendance_profiles
  where user_key = p_target_user_key
  for update;
  if not found then
    raise exception 'Uživatel nebyl nalezen.';
  end if;

  if v_target_role = 'admin' then
    select count(*) into v_other_admins
    from public.attendance_profiles
    where role = 'admin' and user_key <> p_target_user_key;
    if v_other_admins = 0 then
      raise exception 'Operaci nelze provést: Nelze smazat posledního administrátora v systému.';
    end if;
  end if;

  delete from public.attendance_invites where created_by = p_target_user_key;
  delete from public.attendance_profiles where user_key = p_target_user_key;

  perform public.log_attendance_security_event(
    'admin_delete_user',
    p_target_user_key,
    jsonb_build_object('role', v_target_role)
  );
  return true;
end;
$$;

