create or replace function public.assert_admin_step_up(p_admin_pin text)
returns text
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_user_key text;
  v_hash text;
begin
  v_user_key := public.current_session_user_key();
  if v_user_key = '' or not public.is_admin() then
    raise exception 'Přístup odepřen.';
  end if;
  if p_admin_pin is null or length(p_admin_pin) < 1 then
    raise exception 'Pro tuto operaci je nutné znovu zadat PIN/heslo správce.';
  end if;

  select pin_password_hash into v_hash
  from public.attendance_credentials
  where user_key = v_user_key;

  if v_hash is null or not coalesce(crypt(p_admin_pin, v_hash) = v_hash, false) then
    raise exception 'Ověření správce selhalo.';
  end if;

  return v_user_key;
end;
$$;

